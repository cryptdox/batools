#!/usr/bin/env python3
"""
Writes islamic_studio_quizbank.sql: the big quiz bank (quizbank_a.py and
quizbank_b.py, 17 quizzes / 170 questions in English and Bangla) and a
60-day challenge over every quiz, the six from islamic_studio_phase2.sql too.

Quizzes go in as 'in_review': approve them in batools → Content Review
(the Read button shows every question and answer first).
Re-runnable: fixed ids, nothing existing is overwritten.

    python3 islamic_studio_quizbank.py
"""
import json
import sys
import uuid
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from quizbank_a import QUIZZES as PART_A  # noqa: E402
from quizbank_b import QUIZZES as PART_B  # noqa: E402

OUT = HERE / 'islamic_studio_quizbank.sql'
NS = uuid.UUID('6f1c1b8e-6c2a-4d4e-9a57-1d2c3b4a5e60')
# The six quizzes of islamic_studio_phase2.sql (same ids), joined into the big challenge.
PHASE2_SLUGS = ['quran-basics', 'prophets', 'pillars-and-salah', 'seerah', 'ramadan', 'islamic-history']
TOPICS = {'quran', 'prophets', 'pillars', 'seerah', 'history', 'fiqh', 'ramadan', 'general'}


def sql(v) -> str:
    if v is None:
        return 'NULL'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, dict):
        v = json.dumps(v, ensure_ascii=False)
    return "'" + str(v).replace("'", "''") + "'"


def uid(kind: str, key: str) -> str:
    return str(uuid.uuid5(NS, f'{kind}:{key}'))


def check(quizzes):
    slugs = [q[0] for q in quizzes] + PHASE2_SLUGS
    assert len(slugs) == len(set(slugs)), 'duplicate quiz slug'
    for slug, title, topic, level, seconds, questions in quizzes:
        assert topic in TOPICS, (slug, topic)
        assert level in ('easy', 'medium', 'hard'), (slug, level)
        assert len(questions) >= 5, slug
        for n, (question, answers, correct, explanation, _source) in enumerate(questions, 1):
            assert len(answers) == 4 and 0 <= correct < 4, (slug, n)
            for text in [question, explanation, title, *answers]:
                assert text['en'].strip() and text['bn'].strip(), (slug, n)
            assert len({a['en'] for a in answers}) == 4, (slug, n, 'repeated answer')


def build(quizzes) -> str:
    out = ["""-- Islamic Studio quiz bank: 17 quizzes, 170 questions (English and Bangla), and a
-- 60-day challenge over all 23 quizzes. Generated by islamic_studio_quizbank.py.
-- Run after islamic_studio_phase2.sql. Safe to run again. Approve the quizzes in
-- batools → Islamic Studio → Content Review.

BEGIN;
"""]
    for order, (slug, title, topic, level, seconds, questions) in enumerate(quizzes, 7):
        qid = uid('quiz', slug)
        out.append(f'\n-- {title["en"]}')
        out.append(
            'INSERT INTO is_quizzes (id, title, topic, difficulty, time_limit_seconds, points_per_question, review_status, sort_order) VALUES ('
            f"{sql(qid)}, {sql(title)}, {sql(topic)}, {sql(level)}, {sql(seconds)}, 10, 'in_review', {order}) ON CONFLICT (id) DO NOTHING;")
        for n, (question, answers, correct, explanation, source) in enumerate(questions, 1):
            question_id = uid('question', f'{slug}:{n}')
            out.append(
                'INSERT INTO is_quiz_questions (id, quiz_id, question, explanation, source_ref, sort_order) VALUES ('
                f"{sql(question_id)}, {sql(qid)}, {sql(question)}, {sql(explanation)}, {sql(source)}, {n}) ON CONFLICT (id) DO NOTHING;")
            values = ', '.join(
                f"({sql(uid('option', f'{slug}:{n}:{k}'))}, {sql(question_id)}, {sql(a)}, {sql(k == correct)}, {k + 1})"
                for k, a in enumerate(answers))
            out.append(f'INSERT INTO is_quiz_options (id, question_id, text, is_correct, sort_order) VALUES {values} ON CONFLICT (id) DO NOTHING;')

    all_ids = [uid('quiz', s) for s in PHASE2_SLUGS] + [uid('quiz', q[0]) for q in quizzes]
    out.append('\n-- The big challenge: every quiz, 60 days from when this runs (only quizzes that exist count).')
    out.append(
        'INSERT INTO is_challenges (id, title, description, quiz_ids, starts_at, ends_at) SELECT '
        f"{sql(uid('challenge', 'big-quiz'))}, {sql({'en': 'The Big Islamic Quiz', 'bn': 'বড় ইসলামিক কুইজ'})}, "
        f"{sql({'en': 'All 23 quizzes. Your best score on each counts; climb the leaderboard!', 'bn': '২৩টি কুইজ। প্রতিটিতে আপনার সেরা স্কোর গণনা হবে; লিডারবোর্ডে উঠে আসুন!'})}, "
        f"ARRAY(SELECT id FROM is_quizzes WHERE id IN ({', '.join(sql(i) + '::uuid' for i in all_ids)}) ORDER BY sort_order), now(), now() + interval '60 days' "
        'ON CONFLICT (id) DO NOTHING;')
    out.append("""
COMMIT;

SELECT 'quizzes' AS what, count(*) FROM is_quizzes
UNION ALL SELECT 'questions', count(*) FROM is_quiz_questions
UNION ALL SELECT 'answers', count(*) FROM is_quiz_options
UNION ALL SELECT 'quizzes waiting for review', count(*) FROM is_quizzes WHERE review_status = 'in_review';
""")
    return '\n'.join(out)


if __name__ == '__main__':
    quizzes = PART_A + PART_B
    check(quizzes)
    OUT.write_text(build(quizzes))
    print(f'✔ {OUT.name}: {len(quizzes)} quizzes, {sum(len(q[5]) for q in quizzes)} questions ({OUT.stat().st_size // 1024} KB)')
